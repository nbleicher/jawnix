def generate_grid_cells(bbox_str: str, cell_size_km: float) -> list:
    """Parse 'minLat,minLon,maxLat,maxLon' → list of 'lat,lon' cell centers."""
    if cell_size_km <= 0:
        cell_size_km = 1.0
    parts = [float(x.strip()) for x in bbox_str.split(",")]
    if len(parts) != 4:
        raise ValueError(f"bbox must be 'minLat,minLon,maxLat,maxLon', got: {bbox_str!r}")
    min_lat, min_lon, max_lat, max_lon = parts
    lat_step = cell_size_km / KM_PER_DEGREE_LAT
    mid_lat = (min_lat + max_lat) / 2
    cos_mid = max(abs(math.cos(math.radians(mid_lat))), 1e-6)
    lon_step = cell_size_km / (KM_PER_DEGREE_LAT * cos_mid)
    cells = []
    lat = min_lat + lat_step / 2
    while lat < max_lat:
        lon = min_lon + lon_step / 2
        while lon < max_lon:
            cells.append(f"{lat:.6f},{lon:.6f}")
            lon += lon_step
        lat += lat_step
    return cells
